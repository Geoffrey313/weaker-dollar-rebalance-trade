"""Shared academic figure style, palette, and save helper.

Every figure of both manuscripts uses one palette with a fixed meaning:

  NAVY   the main series or estimate: event-study coefficients, the tariff and the border
         price, dollar invoicing, and an open capital account;
  BRICK  the comparison series: in the structural figures, capital controls or a closed account;
  GREY   benchmarks, reference lines, and the estimate's confidence region.

A comparison series is also drawn dashed or with a different marker, so figures remain legible
in grayscale and for readers with color-vision deficiencies. Confidence bands and regions are
light grey (GREY_TINT); the light navy and brick tints fill the area under a density. When LaTeX is installed, every label is typeset by LaTeX in Latin
Modern, the font of the manuscripts, and embedded as Type 1 fonts; otherwise the style falls back
to DejaVu Serif with Computer Modern mathematics. Figures are drawn at the text width of the manuscripts
(TEXT_WIDTH inches) and included at the full text width, so that their type matches the size of
the figure notes. French figures use the decimal comma. Figures are generated by code and never
edited by hand.
"""
